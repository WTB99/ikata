export const dictionaries: Record<Lang, Dict> = { uk, ru };

export const getDict = (lang: Lang) => dictionaries[lang];

export const alternateLinks = () => [
  { rel: "alternate", hreflang: "uk", href: `${SITE_URL}/` },
  { rel: "alternate", hreflang: "ru", href: `${SITE_URL}/ru` },
  { rel: "alternate", hreflang: "x-default", href: `${SITE_URL}/` },
];

const jsonLdForLang = (lang: Lang) => {
  const d = getDict(lang);
  const url = `${SITE_URL}${lang === "uk" ? "/" : "/ru"}`;
  const faqPage = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: d.faq.items.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };
  const service = {
    "@context": "https://schema.org",
    "@type": "Service",
    name: "Ikata Proxy",
    description: d.meta.description,
    url,
    provider: { "@type": "Organization", name: "Ikata Proxy", url: SITE_URL },
    aggregateRating: {
      "@type": "AggregateRating",
      ratingValue: "5",
      bestRating: "5",
      reviewCount: "212",
    },
    review: d.reviews.items.map((r) => ({
      "@type": "Review",
      name: r.title,
      reviewBody: r.text,
      author: { "@type": "Person", name: r.name },
      reviewRating: { "@type": "Rating", ratingValue: "5", bestRating: "5" },
    })),
  };
  return [
    { type: "application/ld+json", children: JSON.stringify(faqPage) },
    { type: "application/ld+json", children: JSON.stringify(service) },
  ];
};

export const headForLang = (lang: Lang) => {
  const d = getDict(lang);
  const url = `${SITE_URL}${lang === "uk" ? "/" : "/ru"}`;
  return {
    meta: [
      { title: d.meta.title },
      { name: "description", content: d.meta.description },
      { property: "og:title", content: d.meta.title },
      { property: "og:description", content: d.meta.description },
      { property: "og:type", content: "website" },
      { property: "og:url", content: url },
      { property: "og:locale", content: lang === "uk" ? "uk_UA" : "ru_RU" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
    links: [{ rel: "canonical", href: url }, ...alternateLinks()],
    scripts: jsonLdForLang(lang),
  };
};
